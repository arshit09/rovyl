export type TranslationKey = keyof typeof translations.en;

/**
 * Every declared language has a table, and every table carries the full English key set. Both are
 * checked right here, at compile time, because the alternative is a `t()` that silently returns a
 * raw key like `bgDimmingDesc` as UI text — which is what the old ten-locale table did, at a
 * parity of 429/281/257 keys (TODO §6.3).
 */
const _tablesCoverEveryLanguage: Record<SupportedLanguage, Record<TranslationKey, string>> =
  translations;
void _tablesCoverEveryLanguage;

export function t(key: TranslationKey, lang: SupportedLanguage = FALLBACK_LANGUAGE): string {
  const table: Record<TranslationKey, string> = translations[normalizeLanguage(lang)];
  return table[key] || translations.en[key] || key;
}

/**
 * The same lookup, with `{name}` slots filled in.
 *
 * Templates rather than concatenation, because the operands move: `Version {version} is ready`
 * puts the number in the middle and 「バージョン {version} の準備ができました」 keeps it there, but
 * `Key {key}` becomes 「{key} キー」 — the label crosses to the other side of the value. Building
 * these by joining strings would make that untranslatable.
 *
 * An unknown slot is left standing rather than blanked: `{version}` on screen is a bug someone
 * reports, an empty gap is one nobody notices.
 */
export function tf(
  key: TranslationKey,
  vars: Record<string, string | number>,
  lang: SupportedLanguage = FALLBACK_LANGUAGE,
): string {
  return t(key, lang).replace(/\{(\w+)\}/g, (slot, name: string) =>
    name in vars ? String(vars[name]) : slot,
  );
}
