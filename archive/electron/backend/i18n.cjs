const LANGS = Object.keys(TABLES);

/** One value for the whole process: `select-file` and friends are registered at module scope and
 *  cannot see the window's `currentSettings`, so the language cannot live in that closure. */
let current = "en";

function setLanguage(code) {
  current = typeof code === "string" && Object.prototype.hasOwnProperty.call(TABLES, code) ? code : "en";
  return current;
}

function getLanguage() {
  return current;
}

/**
 * `{name}` slots filled from `vars`. An unknown key returns the key, an unknown slot is left
 * standing — both are louder in a bug report than a blank, and neither throws in front of a user.
 */
function t(key, vars) {
  const table = TABLES[current] || TABLES.en;
  const value = table[key] || TABLES.en[key] || key;
  if (!vars) return value;
  return String(value).replace(/\{(\w+)\}/g, (slot, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : slot,
  );
}

module.exports = { LANGS, TABLES, setLanguage, getLanguage, t };
